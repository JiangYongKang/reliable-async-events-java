package com.github.highcumontoa.reliableasynceventsjava.storage;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.InitializingBean;
import org.springframework.jdbc.core.JdbcTemplate;

import javax.sql.DataSource;

/**
 * 建表（全部语句幂等，可重复执行）。
 *
 * <p>表设计要点：</p>
 * <ul>
 *   <li>outbox_event.idempotency_key 唯一约束：同键重复提交只会有一条事件；</li>
 *   <li>outbox_event.version 乐观锁：并发领取/更新不互相覆盖；</li>
 *   <li>processed_event 消费端去重：处理器副作用只生效一次；</li>
 *   <li>outbox_event_transition 流转流水：每次状态变化可查询、原因可解释。</li>
 * </ul>
 */
public class SchemaInitializer implements InitializingBean {

    private static final Logger log = LoggerFactory.getLogger(SchemaInitializer.class);

    private final JdbcTemplate jdbc;

    public SchemaInitializer(DataSource dataSource) {
        this.jdbc = new JdbcTemplate(dataSource);
    }

    public void initialize() {        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS outbox_event (
                  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  idempotency_key VARCHAR(128) NOT NULL UNIQUE,
                  type            VARCHAR(128) NOT NULL,
                  payload         CLOB         NOT NULL,
                  status          VARCHAR(32)  NOT NULL,
                  dead_reason     VARCHAR(32),
                  error_detail    VARCHAR(1024),
                  attempts        INT          NOT NULL DEFAULT 0,
                  max_attempts    INT          NOT NULL DEFAULT 5,
                  next_attempt_at TIMESTAMP    NOT NULL,
                  claim_token     VARCHAR(64),
                  claimed_at      TIMESTAMP,
                  version         BIGINT       NOT NULL DEFAULT 0,
                  created_at      TIMESTAMP    NOT NULL,
                  updated_at      TIMESTAMP    NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS outbox_event_transition (
                  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  event_id    BIGINT       NOT NULL,
                  from_status VARCHAR(32),
                  to_status   VARCHAR(32)  NOT NULL,
                  reason      VARCHAR(48)  NOT NULL,
                  detail      VARCHAR(1024),
                  attempts    INT          NOT NULL,
                  created_at  TIMESTAMP    NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS processed_event (
                  event_id     BIGINT PRIMARY KEY,
                  processed_at TIMESTAMP NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS orders (
                  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  request_id  VARCHAR(128) NOT NULL UNIQUE,
                  product     VARCHAR(128) NOT NULL,
                  quantity    INT          NOT NULL,
                  created_at  TIMESTAMP    NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS order_projection (
                  order_id    BIGINT PRIMARY KEY,
                  product     VARCHAR(128) NOT NULL,
                  quantity    INT          NOT NULL,
                  projected_at TIMESTAMP   NOT NULL
                )
                """);
        log.info("[schema] 事件 outbox / 流转流水 / 消费去重 / 演示订单表 初始化完成");
    }

    @Override
    public void afterPropertiesSet() {
        initialize();
    }
}
